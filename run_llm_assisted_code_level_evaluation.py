import argparse
import csv
import os
import re
import time
from dataclasses import dataclass
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple, Union

from openpyxl import Workbook, load_workbook
from tqdm import tqdm

from Requirement_Agent.openai_client import get_openai_client


SYSTEM_PROMPT = (
    "You are an experienced software requirement evaluation expert, specializing "
    "in assessing whether model-generated texts accurately reflect the original "
    "software requirements."
)

EVAL_PROMPT_TEMPLATE = """
You will see a pair of texts:
Ground Truth: This is the actual requirement description linked to the project code.
Generated: This is a requirement summary generated by a large language model based on the code.

Your task is to evaluate the Generated requirement across the following four dimensions. For each dimension, first provide a detailed explanation (in English), and then assign a score:
1. Completeness: The extent to which the generated text covers all core elements of the original requirement.
2. Conciseness: The degree to which the expression is clear and succinct, without unnecessary redundancy.
3. Correctness: The absence of misunderstandings, hallucinations, or content that contradicts the ground truth.
4. Cohesiveness: The degree to which the sentences are logically connected, coherent, and smoothly articulated.

Please follow the steps below when answering:
First, reason through and explain each dimension (in English)
Then give a score for each dimension (1 to 5, integers only)
Finally, provide an overall score (average of the four dimensions, rounded to one decimal place)

Format Example:
[Dimension 1: Completeness]
Explanation:
...
Score: X

[Dimension 2: Conciseness]
Explanation:
...
Score: X

...

[Overall Score]
Average: X.X

Please strictly follow the format above.

Ground Truth:
{reference}

Generated:
{generated}
""".strip()

DIMENSIONS = ["Completeness", "Conciseness", "Correctness", "Cohesiveness"]
EVALUATION_COLUMNS = DIMENSIONS + ["Average", "FullEvaluation"]
EXCEL_CELL_LIMIT = 32767


@dataclass
class TableData:
    headers: List[str]
    rows: List[List[str]]


def normalize_cell(value: object) -> str:
    if value is None:
        return ""
    return str(value)


def make_unique_headers(headers: Sequence[str]) -> List[str]:
    seen: Dict[str, int] = {}
    unique_headers: List[str] = []
    for index, header in enumerate(headers, start=1):
        base = normalize_cell(header).strip() or f"Column{index}"
        count = seen.get(base, 0)
        seen[base] = count + 1
        unique_headers.append(base if count == 0 else f"{base}_{count + 1}")
    return unique_headers


def read_csv_table(path: Path, has_header: bool) -> TableData:
    text: Optional[str] = None
    for encoding in ("utf-8-sig", "utf-8", "gbk", "cp1252"):
        try:
            text = path.read_text(encoding=encoding)
            break
        except UnicodeDecodeError:
            continue
    if text is None:
        raise UnicodeDecodeError("csv", b"", 0, 1, f"Cannot decode CSV file: {path}")

    rows = list(csv.reader(text.splitlines()))
    if not rows:
        raise ValueError(f"Input table is empty: {path}")

    if has_header:
        headers = make_unique_headers(rows[0])
        data_rows = rows[1:]
    else:
        max_columns = max(len(row) for row in rows)
        headers = [f"Column{index}" for index in range(1, max_columns + 1)]
        data_rows = rows
    return TableData(headers=headers, rows=[[normalize_cell(cell) for cell in row] for row in data_rows])


def read_xlsx_table(path: Path, has_header: bool, sheet_name: Optional[str]) -> TableData:
    workbook = load_workbook(path, data_only=True, read_only=True)
    worksheet = workbook[sheet_name] if sheet_name else workbook.worksheets[0]
    rows = [
        [normalize_cell(cell) for cell in row]
        for row in worksheet.iter_rows(values_only=True)
    ]
    rows = [row for row in rows if any(cell.strip() for cell in row)]
    if not rows:
        raise ValueError(f"Input table is empty: {path}")

    if has_header:
        headers = make_unique_headers(rows[0])
        data_rows = rows[1:]
    else:
        max_columns = max(len(row) for row in rows)
        headers = [f"Column{index}" for index in range(1, max_columns + 1)]
        data_rows = rows
    return TableData(headers=headers, rows=data_rows)


def pad_rows(table: TableData) -> TableData:
    width = len(table.headers)
    padded_rows = [row + [""] * (width - len(row)) for row in table.rows]
    return TableData(headers=table.headers, rows=[row[:width] for row in padded_rows])


def load_input_table(path: str, has_header: bool, sheet_name: Optional[str]) -> TableData:
    input_path = Path(path)
    suffix = input_path.suffix.lower()
    if suffix == ".csv":
        table = read_csv_table(input_path, has_header=has_header)
    elif suffix in {".xlsx", ".xlsm"}:
        table = read_xlsx_table(input_path, has_header=has_header, sheet_name=sheet_name)
    else:
        raise ValueError("Input table must be .csv, .xlsx, or .xlsm")
    return pad_rows(table)


def resolve_column(column: Union[str, int], headers: Sequence[str]) -> int:
    if isinstance(column, int):
        index = column - 1
    else:
        column_text = column.strip()
        if column_text.isdigit():
            index = int(column_text) - 1
        else:
            if column_text not in headers:
                raise ValueError(
                    f"Column {column_text!r} not found. Available columns: {list(headers)}"
                )
            index = list(headers).index(column_text)
    if index < 0 or index >= len(headers):
        raise ValueError(f"Column index out of range: {column}")
    return index


def round_half_up(value: float, digits: int = 1) -> float:
    quantizer = Decimal("1") if digits == 0 else Decimal("1").scaleb(-digits)
    return float(Decimal(str(value)).quantize(quantizer, rounding=ROUND_HALF_UP))


def extract_scores(evaluation_text: str) -> Dict[str, Optional[float]]:
    scores: Dict[str, Optional[float]] = {}
    for dimension in DIMENSIONS:
        pattern = rf"{dimension}.*?\*{{0,2}}Score\*{{0,2}}\s*[:：]\s*([1-5])"
        match = re.search(pattern, evaluation_text, flags=re.IGNORECASE | re.DOTALL)
        scores[dimension] = int(match.group(1)) if match else None

    average_match = re.search(
        r"\*{0,2}Average\*{0,2}\s*[:：]\s*([0-9]+(?:\.[0-9]+)?)",
        evaluation_text,
        flags=re.IGNORECASE,
    )
    parsed_average = float(average_match.group(1)) if average_match else None
    dimension_values = [scores[dimension] for dimension in DIMENSIONS]
    if all(value is not None for value in dimension_values):
        parsed_average = round_half_up(sum(dimension_values) / len(dimension_values), 1)
    scores["Average"] = parsed_average
    return scores


def call_evaluator(
    reference: str,
    generated: str,
    model: str,
    temperature: float,
    max_tokens: int,
) -> str:
    prompt = EVAL_PROMPT_TEMPLATE.format(
        reference=reference.strip(),
        generated=generated.strip(),
    )
    response = get_openai_client().chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": prompt},
        ],
        temperature=temperature,
        max_tokens=max_tokens,
    )
    return response.choices[0].message.content.strip()


def evaluate_row(
    reference: str,
    generated: str,
    model: str,
    temperature: float,
    max_tokens: int,
    max_retries: int,
    retry_sleep: float,
) -> Dict[str, object]:
    last_error: Optional[Exception] = None
    for attempt in range(max_retries + 1):
        try:
            full_evaluation = call_evaluator(
                reference=reference,
                generated=generated,
                model=model,
                temperature=temperature,
                max_tokens=max_tokens,
            )
            scores = extract_scores(full_evaluation)
            scores["FullEvaluation"] = full_evaluation
            return scores
        except Exception as error:  # Keep long runs from losing all completed rows.
            last_error = error
            if attempt < max_retries:
                time.sleep(retry_sleep * (2**attempt))

    result: Dict[str, object] = {column: None for column in EVALUATION_COLUMNS}
    result["FullEvaluation"] = f"ERROR: {last_error}"
    return result


def remove_existing_evaluation_columns(table: TableData) -> TableData:
    keep_indices = [
        index
        for index, header in enumerate(table.headers)
        if header not in EVALUATION_COLUMNS
    ]
    headers = [table.headers[index] for index in keep_indices]
    rows = [[row[index] for index in keep_indices] for row in table.rows]
    return TableData(headers=headers, rows=rows)


def validate_excel_lengths(headers: Sequence[str], rows: Sequence[Sequence[object]]) -> None:
    for row_index, row in enumerate([headers, *rows], start=1):
        for column_index, value in enumerate(row, start=1):
            text = "" if value is None else str(value)
            if len(text) > EXCEL_CELL_LIMIT:
                raise ValueError(
                    "Cannot write an unchanged .xlsx because cell "
                    f"R{row_index}C{column_index} has {len(text)} characters, "
                    f"exceeding Excel's {EXCEL_CELL_LIMIT}-character cell limit."
                )


def write_xlsx(path: str, headers: Sequence[str], rows: Sequence[Sequence[object]]) -> None:
    validate_excel_lengths(headers, rows)
    output_path = Path(path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    workbook = Workbook()
    worksheet = workbook.active
    worksheet.title = "Sheet1"
    worksheet.append(list(headers))
    for row in rows:
        worksheet.append(list(row))
    workbook.save(output_path)


def run_llm_assisted_code_level_evaluation(
    input_table: str,
    output_xlsx: str,
    reference_col: Union[str, int] = 2,
    generated_col: Union[str, int] = 3,
    sheet_name: Optional[str] = None,
    has_header: bool = True,
    model: Optional[str] = None,
    temperature: float = 0.0,
    max_tokens: int = 1000,
    max_retries: int = 3,
    retry_sleep: float = 2.0,
) -> None:
    model_name = model or os.getenv("UI_REQGEN_EVAL_MODEL", "gpt-4o")
    table = load_input_table(input_table, has_header=has_header, sheet_name=sheet_name)
    table = remove_existing_evaluation_columns(table)

    if len(table.headers) < 3:
        raise ValueError(
            "The input table must contain at least three columns: code, reference text, "
            "and generated text."
        )

    reference_index = resolve_column(reference_col, table.headers)
    generated_index = resolve_column(generated_col, table.headers)
    output_headers = table.headers + EVALUATION_COLUMNS
    output_rows: List[List[object]] = []

    for row in tqdm(table.rows, desc="Evaluating code-level requirements"):
        reference = row[reference_index]
        generated = row[generated_index]
        evaluation = evaluate_row(
            reference=reference,
            generated=generated,
            model=model_name,
            temperature=temperature,
            max_tokens=max_tokens,
            max_retries=max_retries,
            retry_sleep=retry_sleep,
        )
        output_rows.append(row + [evaluation.get(column) for column in EVALUATION_COLUMNS])

    write_xlsx(output_xlsx, output_headers, output_rows)
    print(f"[DONE] Saved LLM-assisted evaluation results to {output_xlsx}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Run the paper-aligned LLM-assisted code-level requirement evaluation. "
            "The input table is external to the replication package and is expected "
            "to contain code, reference text, and generated text in its first three "
            "columns by default."
        )
    )
    parser.add_argument("--input-table", required=True, help="Input .csv/.xlsx/.xlsm table")
    parser.add_argument("--output-xlsx", required=True, help="Output .xlsx path")
    parser.add_argument(
        "--reference-col",
        default="2",
        help="Reference-text column name or 1-based index. Default: 2",
    )
    parser.add_argument(
        "--generated-col",
        default="3",
        help="Generated-text column name or 1-based index. Default: 3",
    )
    parser.add_argument("--sheet-name", default=None, help="Worksheet name for Excel input")
    parser.add_argument(
        "--no-header",
        action="store_true",
        help="Use when the input table has no header row.",
    )
    parser.add_argument(
        "--model",
        default=None,
        help="Evaluator model. Defaults to UI_REQGEN_EVAL_MODEL or gpt-4o.",
    )
    parser.add_argument("--temperature", type=float, default=0.0)
    parser.add_argument("--max-tokens", type=int, default=1000)
    parser.add_argument("--max-retries", type=int, default=3)
    parser.add_argument("--retry-sleep", type=float, default=2.0)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    run_llm_assisted_code_level_evaluation(
        input_table=args.input_table,
        output_xlsx=args.output_xlsx,
        reference_col=args.reference_col,
        generated_col=args.generated_col,
        sheet_name=args.sheet_name,
        has_header=not args.no_header,
        model=args.model,
        temperature=args.temperature,
        max_tokens=args.max_tokens,
        max_retries=args.max_retries,
        retry_sleep=args.retry_sleep,
    )


if __name__ == "__main__":
    main()
